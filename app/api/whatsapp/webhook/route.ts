import { NextRequest, NextResponse } from "next/server";
import { processUserMessage } from "@/lib/aiBrain";

// 1. GET: Webhook verification for Meta WhatsApp Cloud API
export async function GET(req: NextRequest) {
  const searchParams = req.nextUrl.searchParams;
  const mode = searchParams.get("hub.mode");
  const token = searchParams.get("hub.verify_token");
  const challenge = searchParams.get("hub.challenge");

  const verifyToken = process.env.WHATSAPP_VERIFY_TOKEN || "meshk_secret_verify_token_2026";

  if (mode === "subscribe" && token === verifyToken) {
    console.log("WhatsApp Webhook verified successfully!");
    return new Response(challenge, { status: 200 });
  }

  return NextResponse.json({ error: "Verification token mismatch" }, { status: 403 });
}

// 2. POST: Receive incoming WhatsApp message and respond using AI Brain
export async function POST(req: NextRequest) {
  try {
    const body = await req.json();

    // Meta WhatsApp Cloud API webhook structure
    const entry = body?.entry?.[0];
    const changes = entry?.changes?.[0];
    const value = changes?.value;
    const message = value?.messages?.[0];

    if (!message) {
      // Return 200 for delivery receipts, read status, etc.
      return NextResponse.json({ status: "acknowledged" }, { status: 200 });
    }

    const from = message.from; // User's WhatsApp phone number
    const messageBody = message.text?.body; // User's message text

    if (!messageBody) {
      return NextResponse.json({ status: "ignored_non_text" }, { status: 200 });
    }

    console.log(`Received WhatsApp message from ${from}: ${messageBody}`);

    // Process message with AI Brain
    const aiResult = await processUserMessage(messageBody);

    // If WHATSAPP_ACCESS_TOKEN & WHATSAPP_PHONE_NUMBER_ID are configured in environment variables,
    // send direct automated reply back to the user via Meta Cloud API!
    const whatsappToken = process.env.WHATSAPP_ACCESS_TOKEN;
    const phoneNumberId = process.env.WHATSAPP_PHONE_NUMBER_ID;

    if (whatsappToken && phoneNumberId) {
      await fetch(
        `https://graph.facebook.com/v19.0/${phoneNumberId}/messages`,
        {
          method: "POST",
          headers: {
            Authorization: `Bearer ${whatsappToken}`,
            "Content-Type": "application/json",
          },
          body: JSON.stringify({
            messaging_product: "whatsapp",
            to: from,
            type: "text",
            text: { body: aiResult.reply },
          }),
        }
      );
    } else {
      console.log("Automated WhatsApp reply generated by AI Brain:", aiResult.reply);
    }

    return NextResponse.json({ status: "success", reply: aiResult.reply }, { status: 200 });
  } catch (error) {
    console.error("WhatsApp Webhook processing error:", error);
    return NextResponse.json({ error: "Failed to process message" }, { status: 500 });
  }
}
